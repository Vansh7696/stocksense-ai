/**
 * StockSense AI — Model Prediction Controller (Milestone 5C.6.1)
 * Orchestrates multi-horizon directional model predictions by connecting
 * PostgreSQL historical candle records, Redis caching, and the Python FastAPI ML microservice.
 */

import prisma from '../config/prisma.js';
import cacheService, { CACHE_TTL } from '../services/cache.service.js';
import mlClientService from '../services/mlClient.service.js';
import { resolveStockIdentifier } from './stock.controller.js';
import { AppError } from '../middleware/errorHandler.js';

const ALLOWED_EXCHANGES = new Set(['NSE', 'BSE']);
const ALLOWED_HORIZONS = new Set([1, 3, 5]);

export const PREDICTION_DISCLAIMER =
  'Predictions generated by StockSense AI quantitative machine learning models are intended strictly for educational, research, and technical analysis evaluation. They do not constitute investment advice, trading recommendations, or financial advisory. Market movements are subject to risk, and past model performance or probabilistic outputs do not guarantee future returns.';

/**
 * Human-readable labels and metadata for forecast horizons.
 */
function getHorizonLabel(h) {
  switch (Number(h)) {
    case 1:
      return '1 Trading Day (Next Session Close)';
    case 3:
      return '3 Trading Days (Multi-Session Trend)';
    case 5:
      return '5 Trading Days (1 Calendar Week)';
    default:
      return `${h} Trading Days`;
  }
}

/**
 * GET /api/stocks/:id/predictions
 *
 * Retrieves multi-horizon directional predictions for a stock.
 * 1. Resolves stock by UUID, instrumentToken, or symbol.
 * 2. Fetches the latest 300 daily candles from PostgreSQL in DESCENDING timestamp order.
 * 3. Enforces a minimum of 200 daily sessions for technical indicator warm-up.
 * 4. Checks deterministic Redis cache keyed by stock, exchange, and latest candle timestamp.
 * 5. Reverses candles into ascending chronological order.
 * 6. Dispatches to FastAPI POST /api/predict/multi-horizon via MLServiceClient.
 * 7. Applies financial advisory disclaimer, caches in Redis (TTL: 300s), and returns envelope.
 */
export async function getStockPredictions(req, res, next) {
  try {
    const { id } = req.params;
    const { exchange, horizon } = req.query;

    if (!id || typeof id !== 'string' || id.trim().length === 0) {
      throw new AppError('Stock identifier parameter is required.', 400, 'INVALID_STOCK_ID');
    }

    // 1. Validate optional query parameters
    let exchangeParam;
    if (exchange !== undefined && exchange !== '') {
      exchangeParam = String(exchange).trim().toUpperCase();
      if (!ALLOWED_EXCHANGES.has(exchangeParam)) {
        throw new AppError(
          `Invalid exchange filter "${exchange}". Allowed: ${Array.from(ALLOWED_EXCHANGES).join(', ')}`,
          400,
          'INVALID_EXCHANGE'
        );
      }
    }

    let horizonFilter = null;
    if (horizon !== undefined && horizon !== '' && horizon !== 'all') {
      const parsedH = parseInt(horizon, 10);
      if (!ALLOWED_HORIZONS.has(parsedH)) {
        throw new AppError(
          `Invalid horizon filter "${horizon}". Allowed forecast horizons: 1, 3, 5 trading days.`,
          400,
          'INVALID_HORIZON'
        );
      }
      horizonFilter = parsedH;
    }

    // 2. Resolve stock identifier unambiguously
    const stock = await resolveStockIdentifier(id, exchangeParam, {
      include: {
        exchange: {
          select: {
            id: true,
            code: true,
            name: true,
            currency: true,
            timezone: true,
          },
        },
      },
    });

    // 3. Query latest 300 daily candles from PostgreSQL in DESCENDING timestamp order
    let rawCandles;
    try {
      rawCandles = await prisma.historicalPrice.findMany({
        where: {
          stockId: stock.id,
          interval: '1D',
        },
        orderBy: [
          { timestamp: 'desc' },
          { id: 'desc' },
        ],
        take: 300,
      });
    } catch (dbErr) {
      if (
        dbErr.code === 'P1001' ||
        dbErr.name === 'PrismaClientInitializationError' ||
        dbErr.message?.includes('Can\'t reach database server')
      ) {
        throw new AppError(
          'Database service temporarily unavailable. Failed to query historical market data.',
          503,
          'DATABASE_UNAVAILABLE'
        );
      }
      throw dbErr;
    }

    // 4. Enforce minimum of 200 daily sessions for algorithmic warm-up
    if (!rawCandles || rawCandles.length < 200) {
      throw new AppError(
        `Insufficient historical daily candle data for "${stock.symbol}". At least 200 trading sessions are required for algorithmic feature warm-up (found ${rawCandles ? rawCandles.length : 0}).`,
        400,
        'INSUFFICIENT_HISTORICAL_DATA'
      );
    }

    // 5. Construct deterministic cache key incorporating stock, exchange, and latest candle timestamp
    const latestCandle = rawCandles[0];
    const latestTimestamp = latestCandle.timestamp instanceof Date
      ? latestCandle.timestamp.toISOString()
      : String(latestCandle.timestamp);
    const asOfDate = latestTimestamp.split('T')[0];

    const cacheIdentifier = `${stock.id}:${stock.exchange.code}:${latestTimestamp}:h${horizonFilter || 'all'}`;
    const cacheKey = cacheService.buildKey('stocks:predictions', cacheIdentifier);

    // 6. Check Redis cache (fails open if Redis is unavailable)
    const cachedData = await cacheService.get(cacheKey);
    if (cachedData) {
      return res.status(200).json({
        success: true,
        data: cachedData,
        meta: {
          cached: true,
          timestamp: new Date().toISOString(),
          stock: {
            id: stock.id,
            symbol: stock.symbol,
            companyName: stock.companyName,
            exchange: stock.exchange.code,
          },
        },
      });
    }

    // 7. Reverse raw candles into strict chronological (ascending) order before passing to ML
    const chronologicalCandles = [...rawCandles].reverse();

    // 8. Invoke FastAPI multi-horizon inference service
    const mlResponse = await mlClientService.predictMultiHorizon(stock.symbol, {
      candles: chronologicalCandles,
    });

    // 9. Format structured predictions
    const formattedPredictions = {};
    const horizonsToInclude = horizonFilter ? [horizonFilter] : [1, 3, 5];

    for (const h of horizonsToInclude) {
      const pred = mlResponse.predictions?.[h] || mlResponse.predictions?.[String(h)];
      if (!pred) continue;

      formattedPredictions[h] = {
        horizon: pred.horizon,
        horizonLabel: getHorizonLabel(pred.horizon),
        entryTiming: 'Next Session Open (O[t+1])',
        exitTiming: `Target Session Close (C[t+${pred.horizon}])`,
        targetThresholdPct: pred.target_threshold_pct,
        targetDefinition: `UP if return > +${pred.target_threshold_pct}%, DOWN if return < -${pred.target_threshold_pct}%, else NEUTRAL`,
        predictedClass: pred.predicted_class,
        predictedLabel: pred.predicted_label,
        confidence: pred.confidence,
        probabilities: pred.probabilities,
        model: {
          modelId: pred.model_id,
          algorithm: pred.algorithm,
          artifactSha256: pred.artifact_sha256,
          featureSchemaVersion: pred.feature_schema_version,
        },
        executionTimeMs: pred.execution_time_ms,
      };
    }

    const payload = {
      symbol: stock.symbol,
      exchange: stock.exchange.code,
      asOfDate,
      latestCandleTimestamp: latestTimestamp,
      candlesUsed: chronologicalCandles.length,
      predictions: formattedPredictions,
      disclaimer: PREDICTION_DISCLAIMER,
      totalExecutionTimeMs: mlResponse.total_execution_time_ms,
    };

    // 10. Cache in Redis (TTL: 5 minutes / 300 seconds, fails open)
    const ttl = CACHE_TTL.STOCK_PREDICTIONS || CACHE_TTL.DEFAULT || 300;
    await cacheService.set(cacheKey, payload, ttl);

    return res.status(200).json({
      success: true,
      data: payload,
      meta: {
        cached: false,
        timestamp: new Date().toISOString(),
        stock: {
          id: stock.id,
          symbol: stock.symbol,
          companyName: stock.companyName,
          exchange: stock.exchange.code,
        },
      },
    });
  } catch (err) {
    next(err);
  }
}

/**
 * GET /api/stocks/predictions/models
 *
 * Introspects currently active champion models declared in the FastAPI microservice.
 * Returns algorithm families, horizons, target thresholds, and cryptographic SHA-256 digests.
 */
export async function getActiveModelChampions(req, res, next) {
  try {
    const cacheKey = cacheService.buildKey('stocks:predictions:models', 'active');
    const cachedData = await cacheService.get(cacheKey);

    if (cachedData) {
      return res.status(200).json({
        success: true,
        data: cachedData,
        meta: {
          cached: true,
          timestamp: new Date().toISOString(),
        },
      });
    }

    const mlResponse = await mlClientService.getActiveModels();

    const ttl = CACHE_TTL.STOCK_PREDICTIONS || CACHE_TTL.DEFAULT || 300;
    await cacheService.set(cacheKey, mlResponse, ttl);

    return res.status(200).json({
      success: true,
      data: mlResponse,
      meta: {
        cached: false,
        timestamp: new Date().toISOString(),
      },
    });
  } catch (err) {
    next(err);
  }
}
